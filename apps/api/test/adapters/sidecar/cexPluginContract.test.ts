import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { validateManifest } from "@retrowatchdog/shared";
import { parseSyncRow } from "../../../src/adapters/sidecar/protocol.js";
import type { CatalogItemUpsert } from "../../../src/adapters/types.js";

/**
 * The joint between the app and the CeX plugin, checked with fixtures because
 * there is no compiler between them any more.
 *
 * The plugin's own tests prove it builds the rows and the manifest it means to
 * (`retrowatchdog-cex-plugin/test/`). This proves the APP accepts them, and that it
 * reads them as EXACTLY what the deleted in-app CeX adapter produced for the
 * same Algolia hits, frozen in a fixture below.
 *
 * DERIVED, not hand-written, on the eBay plugin's precedent
 * (`ebayPluginContract.test.ts`): both fixtures were produced by running the
 * plugin's own committed code over the plugin's own committed Algolia answer —
 * `manifestPayload()` for the manifest, `rowsFrom()` for the rows — with no
 * network and no keys. Regenerate them with a script physically INSIDE
 * `retrowatchdog-cex-plugin/`, because a relative ESM import resolves against the
 * file's own location and never the shell's working directory:
 *
 *   // retrowatchdog-cex-plugin/.gen-fixtures.mts (written, run, deleted)
 *   import { loadSettings } from "./src/config.js";
 *   import { manifestPayload, scheduleFrom } from "./src/manifest.js";
 *   import { rowsFrom } from "./src/rows.js";
 *   // manifest -> ./manifest.fixture.json
 *   // rowsFrom(hits of ./fixtures/algolia-query-snes.json, "GBP")
 *   //   -> ../../apps/api/src/adapters/sidecar/fixtures/cex-plugin-rows-2026-09-17.json
 */

const manifest: unknown = JSON.parse(
  readFileSync(new URL("../../../src/adapters/sidecar/fixtures/cex-manifest.json", import.meta.url), "utf8"),
);

const rows: unknown[] = JSON.parse(
  readFileSync(new URL("../../../src/adapters/sidecar/fixtures/cex-plugin-rows-2026-09-17.json", import.meta.url), "utf8"),
) as unknown[];

/**
 * What the app's OWN built-in CeX adapter produced for those same Algolia hits,
 * frozen the day it was deleted.
 *
 * Generated by running `algoliaHitToCatalogUpsert` from the last commit that
 * still had it (`git show <pre-port>:apps/api/src/adapters/cex/catalogMap.ts`)
 * over the same `algolia-query-snes.json`, one hit in, one row out, in the
 * fixture's own order. It is frozen rather than recomputed because the code
 * that produced it is gone — and that is exactly why it is worth keeping: it is
 * the only remaining record of what this deployment stored for a CeX box before
 * the port, and the equality below is the regression the port risked.
 */
const builtinRows = JSON.parse(
  readFileSync(new URL("../../../src/adapters/sidecar/fixtures/cex-builtin-rows-2026-09-17.json", import.meta.url), "utf8"),
) as CatalogItemUpsert[];

/** The kinds a user approves for a CeX shop. */
const CEX_LIMITS = {
  kinds: new Set(["sell", "cash", "voucher"]),
  currencies: new Set(["GBP"]),
};

describe("the CeX plugin's manifest, through the app's own validator", () => {
  it("is accepted whole, with the three source ids the app already stores data under", () => {
    const result = validateManifest(manifest);
    expect(result.ok).toBe(true);
    if (!result.ok) return;
    expect(result.manifest.sources.map((source) => source.id)).toEqual(["cex", "cex_es", "cex_ie"]);
  });

  it("declares every CeX shop as a sync source with a schedule and a product template", () => {
    const result = validateManifest(manifest);
    if (!result.ok) throw new Error(result.reason);
    for (const source of result.manifest.sources) {
      expect(source.kind).toBe("sync");
      expect(source.family).toBe("cex");
      expect(source.reach).toBe("local");
      expect(source.defaultRegion).toBe("PAL");
      expect(source.kindRoles).toEqual({ sell: "buy_store", cash: "bid", voucher: "bid" });
      // The cadence the app schedules from, and the template a click lands on.
      expect(source.schedule).toEqual({ catalogCron: "0 3 * * 1", trackedRefreshHours: 24 });
      expect(source.productUrl).toMatch(/^https:\/\/\w+\.webuy\.com\/product-detail\?id=\{id\}$/);
    }
  });

  it("keeps the wording the price table already shows for these three kinds", () => {
    // A port that changed a label would change the UI as a side effect of
    // moving code, which is the one thing it must not do.
    const result = validateManifest(manifest);
    if (!result.ok) throw new Error(result.reason);
    const [uk] = result.manifest.sources;
    expect(uk!.kindLabels).toEqual({
      sell: "CeX UK sells for",
      cash: "CeX UK pays cash",
      voucher: "CeX UK pays voucher",
    });
    // and no short labels: the app's own fallback wording heads these blocks.
    expect(uk!.kindLabelsShort).toBeUndefined();
  });
});

describe("the CeX plugin's catalog rows, through the app's own parser", () => {
  it("parses every row the plugin produced for a real Algolia answer", () => {
    expect(rows.length).toBeGreaterThan(0);
    for (const row of rows) {
      const parsed = parseSyncRow(row, CEX_LIMITS);
      expect(parsed.ok, parsed.ok ? "" : parsed.reason).toBe(true);
      if (!parsed.ok) continue;
      expect(parsed.droppedKinds).toEqual([]);
    }
  });

  it("reads them as EXACTLY what the built-in adapter produced for the same hits", () => {
    // THE REGRESSION THIS PORT RISKED. The plugin fetches what the built-in
    // fetched and the app stores what it stored: same ids, same kinds, same
    // amounts to the penny, same currency, same availability. The `observedAt`
    // the plugin adds is the one deliberate difference, and it is checked below
    // rather than ignored.
    expect(rows).toHaveLength(builtinRows.length);
    for (const [index, builtin] of builtinRows.entries()) {
      const parsed = parseSyncRow(rows[index], CEX_LIMITS);
      if (!parsed.ok) throw new Error(parsed.reason);
      expect(parsed.item.sourceProductId).toBe(builtin.sourceProductId);
      expect(parsed.item.title).toBe(builtin.title);
      expect(parsed.item.categoryText ?? null).toBe(builtin.categoryText ?? null);
      expect(parsed.item.prices).toEqual(builtin.prices);
      expect(parsed.item.currency).toBe(builtin.currency);
      expect(parsed.item.available).toBe(builtin.available);
    }
  });
});
