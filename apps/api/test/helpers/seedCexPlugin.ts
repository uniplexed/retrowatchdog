import { readFileSync } from "node:fs";
import type { PluginManifest, PriceKind, SourceId } from "@retrowatchdog/shared";
import type { Db } from "../../src/db/index.js";
import { approvePlugin, getPlugin, insertPlugin } from "../../src/plugins/repo.js";

/**
 * An approved CeX plugin row, for a test that needs the DATABASE to know
 * `cex`, `cex_es` and `cex_ie`.
 *
 * A test that tags a price point `source: "cex"` needs a real row here for that
 * id to resolve to anything: `app.deps.sources` is built from the `plugins`
 * table alone (src/sources/registry.ts), never from a test's injected adapter
 * list.
 *
 * THE MANIFEST IS THE PLUGIN'S OWN, read off its committed
 * `manifest.fixture.json` rather than typed here — and that file is generated by
 * the plugin's own `manifestPayload()` and run through the app's real
 * `validateManifest` in test/adapters/sidecar/cexPluginContract.test.ts. So a
 * suite that leans on this helper leans on what the plugin actually declares.
 *
 * Approval is a person's act in Settings → Plugins. This helper reaches the same
 * database state through the same `insertPlugin` + `approvePlugin` transaction.
 */
const manifest = JSON.parse(
  readFileSync(new URL("../../src/adapters/sidecar/fixtures/cex-manifest.json", import.meta.url), "utf8"),
) as PluginManifest;

/** The three kinds every CeX shop declares a role for, and a user approves. */
const CEX_KINDS: PriceKind[] = ["sell", "cash", "voucher"];

export async function seedCexPlugin(
  db: Db,
  baseUrl = "http://cex-plugin:8000",
): Promise<void> {
  const row = await insertPlugin(db, {
    baseUrl,
    name: manifest.plugin.name,
    version: manifest.plugin.version,
    manifestSeen: manifest,
    // Public endpoint, no credential: `configured` is true by construction,
    // which is what the plugin's own /health answers.
    lastHealth: { status: "ok", protocol: manifest.protocol, configured: true },
  });
  const reviewed = (await getPlugin(db, row.id))!.manifestSeen!;
  const approvedKinds: Record<SourceId, PriceKind[]> = Object.fromEntries(
    manifest.sources.map((source) => [source.id, CEX_KINDS]),
  );
  const result = await approvePlugin(db, row.id, approvedKinds, reviewed);
  if (!result.ok) throw new Error(`seedCexPlugin: approval failed — ${JSON.stringify(result)}`);
}
